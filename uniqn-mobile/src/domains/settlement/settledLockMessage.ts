/**
 * 정산 완료 잠금 안내 문구의 단일 소스.
 *
 * @description 정산이 끝난 근무의 변경 차단은 UI(주간 그리드·확정 스태프 카드) → Repository
 * (확정 스태프·정산·work_logs) → DB 트리거까지 4계층에 걸쳐 있다. 돈이 걸린 값이라 계층 방어
 * 자체는 유지하되, 예전에는 같은 상황에 문구가 4종이라 화면마다 다른 말을 했다:
 *   "이미 정산 완료된 근무 기록입니다" / "정산이 끝난 근무는 변경할 수 없습니다" /
 *   "이미 정산이 완료된 근무 기록은 수정할 수 없습니다" / "정산이 완료된 근무는 시간을 수정할 수 없어요"
 *
 * 그래서 **어투는 하나로 묶되 동작은 구체적으로** 남긴다 — 사용자는 무엇이 막혔는지와
 * 어떻게 풀 수 있는지를 함께 알아야 한다(에러 메시지 공식: 무엇 + 왜 + 어떻게).
 *
 * @param action 막힌 동작을 "~할" 형태로. 예: '시간을 수정할', '노쇼를 취소할'
 *
 * @example
 * settledLockMessage('시간을 수정할')
 * // '정산이 완료된 근무는 시간을 수정할 수 없어요. 정산을 되돌린 뒤 다시 시도해 주세요.'
 */
export function settledLockMessage(action: string): string {
  return `정산이 완료된 근무는 ${action} 수 없어요. 정산을 되돌린 뒤 다시 시도해 주세요.`;
}

/** 이미 정산 완료된 건에 다시 정산을 시도한 경우 — 되돌릴 대상이 아니라 중복 실행이라 문구가 다르다. */
export const ALREADY_SETTLED_MESSAGE = '이미 정산이 완료된 근무예요.';
